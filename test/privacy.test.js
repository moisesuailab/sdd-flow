test('requirement prose is preserved while nine representative credential formats remain detected', () => {
  const prose = [
    'Password: must have at least 8 characters', 'token: expires after one hour',
    'Cookie: sessions must be secure', 'secret: stored in vault',
    'password: should reject empty values', 'password: minimum length is 8',
    'token: must expire after one hour', 'token: should be generated by the service',
    'secret: must never appear in logs', 'Cookie: must use Secure and HttpOnly',
    'Password: deve possuir ao menos oito caracteres', 'token: expira após uma hora',
  ];
  for (const source of prose) {
    assert.deepEqual(privacy.matches(source), [], source);
    assert.equal(privacy.redact(source), source);
    assert.doesNotThrow(() => privacy.assertSafe(source));
  }
  const credentials = [
    ['-----BEGIN PRIVATE KEY-----\nsyntheticPrivateKey731\n-----END PRIVATE KEY-----', 'syntheticPrivateKey731'],
    ['ghp_' + 'A'.repeat(30), 'A'.repeat(30)], ['sk-' + 'B'.repeat(30), 'B'.repeat(30)],
    ['AKIA' + 'C'.repeat(16), 'C'.repeat(16)], ['Authorization: Bearer syntheticBearer731', 'syntheticBearer731'],
    ['Cookie: session=syntheticSession731; mode=testing', 'syntheticSession731'],
    ['https://user:syntheticUrlCredential731@example.test', 'syntheticUrlCredential731'],
    ['eyJabcdefghijk.abcdefghijk.abcdefghijk', 'eyJabcdefghijk'],
    ['DB_PASSWORD="syntheticQuotedCredential731"', 'syntheticQuotedCredential731'],
  ];
  for (const [source, value] of credentials) {
    assert.ok(privacy.matches(source).length);
    assert.equal(privacy.redact(source).includes(value), false);
    assert.throws(() => privacy.assertSafe(source), /Potential credential/);
  }
  for (const source of ['password: "must have at least 8 characters"', 'password="stored in vault"', 'password: exampleRealCredential731', '_authToken=syntheticRegistry731']) {
    assert.ok(privacy.matches(source).length, source);
  }
  for (const value of [{ Authorization: 'Bearer syntheticHeader731' }, { Cookie: 'session=syntheticHeader731' }, { _authToken: 'syntheticHeader731' }]) {
    assert.throws(() => privacy.assertSafe(value), /Potential credential/);
    assert.equal(JSON.stringify(privacy.sanitize(value)).includes('syntheticHeader731'), false);
  }
});

